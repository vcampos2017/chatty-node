SIZE = 9


def pixels(name):
    """[(x, y, 1 or 2), ...] for an icon: 1 = its color, 2 = highlight."""
    out = []
    for y, row in enumerate(ICONS.get(name, ())):
        for x, ch in enumerate(row):
            if ch == "#":
                out.append((x, y, 1))
            elif ch == "+":
                out.append((x, y, 2))
    return out
